const fs = require("fs");
const path = require("path");
const { ethers } = require("ethers");
const { compileContract } = require("./compile");

const ROOT_DIR = path.resolve(__dirname, "..");
const BUILD_DIR = path.join(ROOT_DIR, "build");
const FRONTEND_DIR = path.join(ROOT_DIR, "frontend");
const RPC_URL = process.env.RPC_URL || "http://127.0.0.1:7545";

async function main() {
  const artifact = compileContract();

  console.log(`Connecting to Ganache at ${RPC_URL}...`);
  const provider = new ethers.JsonRpcProvider(RPC_URL);

  const network = await provider.getNetwork();
  const accounts = await provider.listAccounts();
  if (accounts.length === 0) {
    throw new Error("No unlocked accounts found on Ganache.");
  }

  const manufacturerSigner = accounts[0];
  const manufacturerAddress = await manufacturerSigner.getAddress();
  console.log("Chain ID:", network.chainId.toString());
  console.log("Deploying with Manufacturer (Account 0):", manufacturerAddress);

  const factory = new ethers.ContractFactory(artifact.abi, artifact.bytecode, manufacturerSigner);
  const contract = await factory.deploy();
  await contract.waitForDeployment();

  const contractAddress = await contract.getAddress();
  const deployTx = contract.deploymentTransaction();

  console.log("ProductWarrantyRegistry deployed!");
  console.log("Contract Address:", contractAddress);
  console.log("Transaction Hash:", deployTx ? deployTx.hash : "N/A");

  const deploymentInfo = {
    contractName: "ProductWarrantyRegistry",
    address: contractAddress,
    manufacturer: manufacturerAddress,
    chainId: Number(network.chainId),
    rpcUrl: RPC_URL,
    deployedAt: new Date().toISOString(),
    abi: artifact.abi,
  };

  if (!fs.existsSync(BUILD_DIR)) {
    fs.mkdirSync(BUILD_DIR, { recursive: true });
  }
  fs.writeFileSync(
    path.join(BUILD_DIR, "deployment.json"),
    JSON.stringify(deploymentInfo, null, 2)
  );

  if (!fs.existsSync(FRONTEND_DIR)) {
    fs.mkdirSync(FRONTEND_DIR, { recursive: true });
  }
  const frontendConfig = `// Auto-generated by scripts/deploy.js\nwindow.WARRANTY_CONTRACT_CONFIG = ${JSON.stringify(
    {
      address: contractAddress,
      rpcUrl: RPC_URL,
      chainId: Number(network.chainId),
      abi: artifact.abi,
    },
    null,
    2
  )};\n`;
  fs.writeFileSync(path.join(FRONTEND_DIR, "contract-config.js"), frontendConfig);

  console.log("Updated build/deployment.json and frontend/contract-config.js");
}

main().catch((err) => {
  console.error("Deployment failed:", err.message || err);
  process.exit(1);
});
